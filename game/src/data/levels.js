const GRID_SIZE = 32;
const CELL_SIZE = 8;

/** 确保 grid 为 32×32 */
function normalizeGrid(grid) {
  const normalized = grid.map((row) => String(row).padEnd(GRID_SIZE, "0").slice(0, GRID_SIZE));
  while (normalized.length < GRID_SIZE) {
    normalized.push("0".repeat(GRID_SIZE));
  }
  return normalized.slice(0, GRID_SIZE);
}

/** 旋转 90 度 */
function rotate90(grid) {
  const n = grid.length;
  const out = Array(n)
    .fill(null)
    .map(() => Array(n).fill("0"));
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      out[x][n - 1 - y] = grid[y][x];
    }
  }
  return out.map((row) => row.join(""));
}

/** 水平镜像 */
function flipH(grid) {
  return grid.map((row) => [...row].reverse().join(""));
}

/** 垂直镜像 */
function flipV(grid) {
  return [...grid].reverse();
}

/**
 * 获取关卡数据（固定地图，不做随机变换）
 * 起点固定左下角，终点固定右上角
 * @param {number} levelId 1-6
 * @param {number} seed 保留参数，固定为 0 时不做变换
 */
export function getTransformedLevel(levelId, seed = 0) {
  const raw = RAW_LEVELS.find((l) => l.id === levelId);
  if (!raw) return null;

  let grid = normalizeGrid([...raw.grid]);

  // 防御性处理：确保 grid 为 32×32
  while (grid.length < GRID_SIZE) {
    grid.push("0".repeat(GRID_SIZE));
  }
  grid = grid.slice(0, GRID_SIZE).map((row) => String(row).padEnd(GRID_SIZE, "0").slice(0, GRID_SIZE));

  // seed=0 时不变换，使用固定地图
  if (seed !== 0) {
    const rotations = [0, 90, 180, 270];
    const rotation = rotations[seed % 4];
    for (let i = 0; i < rotation / 90; i++) {
      grid = rotate90(grid);
    }
    if ((seed >> 2) & 1) grid = flipH(grid);
    if ((seed >> 3) & 1) grid = flipV(grid);
  }

  let rows = grid.map((r) => [...String(r).padEnd(GRID_SIZE, "0").slice(0, GRID_SIZE)]);
  // 确保 rows 为 32×32
  while (rows.length < GRID_SIZE) {
    rows.push(Array(GRID_SIZE).fill("0"));
  }
  rows = rows.slice(0, GRID_SIZE);

  // 起点：左下角第一个通道格 (0 或 G)，确保在画面内（player 为 1 格，需 y*cell+cell<=MAZE_PX）
  let startX = -1,
    startY = -1;
  for (let y = GRID_SIZE - 1; y >= 0 && startX < 0; y--) {
    const row = rows[y];
    if (!row || row.length < GRID_SIZE) continue;
    for (let x = 0; x < GRID_SIZE && startX < 0; x++) {
      const c = row[x];
      if (c === "0" || c === "G") {
        startX = x;
        startY = Math.min(y, GRID_SIZE - 1); // 确保不超出下边界
        break;
      }
    }
  }

  // 终点：右上角 G 所在位置（从上方开始找第一个 G）
  let goalX = -1,
    goalY = -1;
  for (let y = 0; y < GRID_SIZE && goalX < 0; y++) {
    const row = rows[y];
    if (!row) continue;
    for (let x = 0; x < GRID_SIZE; x++) {
      if (row[x] === "G") {
        goalX = x;
        goalY = y;
        break;
      }
    }
  }

  const obstacles = [];
  for (let y = 0; y < GRID_SIZE; y++) {
    const row = rows[y];
    if (!row) continue;
    for (let x = 0; x < GRID_SIZE; x++) {
      if (row[x] === "X") obstacles.push({ x, y });
    }
  }

  // 边界封闭配置：根据数据决定四面是否封闭，后续可对某面设 false 增加开口难度
  const bounds = raw.bounds ?? { top: true, bottom: true, left: true, right: true };

  return {
    id: raw.id,
    difficulty: raw.difficulty,
    grid: rows,
    start: { x: startX, y: startY },
    goal: { x: goalX, y: goalY },
    obstacles,
    isHard: raw.difficulty === "hard",
    bounds,
  };
}

/** 生成 64×64 缩略图 canvas 用于关卡选择 */
export function renderLevelThumbnail(levelId) {
  try {
    const level = getTransformedLevel(levelId, 0);
    if (!level || !level.grid || level.grid.length < GRID_SIZE) return null;
    const cell = 64 / GRID_SIZE;
    const canvas = document.createElement("canvas");
    canvas.width = 64;
    canvas.height = 64;
    const ctx = canvas.getContext("2d");
    for (let y = 0; y < GRID_SIZE; y++) {
      const row = level.grid[y];
      if (!row) continue;
      for (let x = 0; x < GRID_SIZE; x++) {
        const c = row[x];
        if (c === "1") ctx.fillStyle = "#333333";
        else if (c === "X") ctx.fillStyle = "#FF4444";
        else if (c === "G") ctx.fillStyle = "#00FF00";
        else ctx.fillStyle = "#000000";
        ctx.fillRect(x * cell, y * cell, cell, cell);
      }
    }
    return canvas.toDataURL("image/png");
  } catch (e) {
    return null;
  }
}

export { GRID_SIZE, CELL_SIZE };
