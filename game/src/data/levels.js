/**
 * 关卡数据：32×32 网格，0=通道 1=墙体 G=终点 X=障碍物
 */

function normalizeGrid(rows) {
  const normalized = rows.slice(0, 32).map((row) => String(row).padEnd(32, "0").slice(0, 32));
  while (normalized.length < 32) {
    normalized.push("0".repeat(32));
  }
  return normalized.slice(0, 32);
}

/** 在最外侧添加一圈墙体，提供物理支撑，后续可在数据中留缺口增加难度 */
function addOuterWalls(grid) {
  const result = [];
  for (let y = 0; y < 32; y++) {
    const row = (grid[y] || "").padEnd(32, "0").slice(0, 32);
    if (y === 0 || y === 31) {
      result.push("1".repeat(32));
    } else {
      result.push("1" + row.slice(1, 31) + "1");
    }
  }
  return result;
}

